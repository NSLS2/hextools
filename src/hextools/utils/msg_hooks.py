def _fmt_timestamp(t: float | None) -> str:
    """Format an epoch timestamp as a human-readable local wall-clock time with ms."""
    if t is None:
        return "--:--:--"
    try:
        dt = datetime.fromtimestamp(t)
    except (OverflowError, OSError, ValueError):
        return str(t)
    return f"{dt:%H:%M:%S}.{dt.microsecond // 1000:03d}"

def _fmt_value(value: Any) -> str:
    """Format an argument value for prose (compact, readable)."""
    if value is None:
        return "nothing"
    if isinstance(value, bool):
        return "on" if value else "off"
    if isinstance(value, float):
        # Trim noisy trailing zeros without losing meaningful precision.
        text = f"{value:.6g}"
        return text
    if isinstance(value, str):
        return f"'{value}'" if value else "''"
    if isinstance(value, (list, tuple)):
        inner = ", ".join(_fmt_value(v) for v in value)
        return f"[{inner}]"
    if isinstance(value, dict):
        inner = ", ".join(f"{k}={_fmt_value(v)}" for k, v in value.items())
        return f"{{{inner}}}"
    return str(value)


def _fmt_obj(obj: str | None) -> str:
    """Format a device/object name."""
    if not obj:
        return "the device"
    return f"'{obj}'"


def _fmt_kwargs(kwargs: dict[str, Any], *, skip: Iterable[str] = ()) -> str:
    """Format kwargs into a trailing clause, skipping bookkeeping keys like 'group'."""
    skip = set(skip)
    items = {k: v for k, v in (kwargs or {}).items() if k not in skip}
    if not items:
        return ""
    parts = [f"{k}={_fmt_value(v)}" for k, v in items.items()]
    return " with " + ", ".join(parts)


def _join_names(items: Iterable[str]) -> str:
    """Join pre-formatted phrases into an English list with an Oxford comma."""
    items = list(items)
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    if len(items) == 2:
        return f"{items[0]} and {items[1]}"
    return ", ".join(items[:-1]) + f", and {items[-1]}"


class GroupLabeler:
    """
    Maps bluesky group ids to friendly labels for narration. Auto-generated ids (random
    UUIDs, as ``mv``/``abs_set``/``stage_all`` create by default) are named after the
    *command* that opened the group -- e.g. a ``stage_all`` group becomes ``stage`` and a
    ``kickoff_all`` group becomes ``kickoff``. If more than one auto group for the same
    command is open at once, later ones are disambiguated with a number (``stage 2``).
    Group names the user chose explicitly (e.g. ``abs_set(motor, 1, group="align")``) are
    recognized as non-random and preserved verbatim.

    ``label`` returns the bare token (``stage``, ``stage 2``, ``align``); callers add the
    surrounding wording (e.g. ``f"group '{label}'"``).
    """

    # bluesky auto group ids are ``str(uuid4())`` or its 32-char hex form.
    _HEX32 = _re.compile(r"\A[0-9a-fA-F]{32}\Z")

    def __init__(self) -> None:
        self._labels: dict[str, str] = {}
        self._active: dict[str, int] = {}  # base command -> count of currently-open groups
        self._auto: set = set()            # group ids that were auto-generated

    @classmethod
    def _looks_autogenerated(cls, group: str) -> bool:
        try:
            _uuid.UUID(group)
            return True
        except (ValueError, AttributeError, TypeError):
            return bool(cls._HEX32.match(group)) if isinstance(group, str) else False

    def label(self, group: str | None, command: str | None = None) -> str | None:
        if group is None:
            return None
        if group not in self._labels:
            if self._looks_autogenerated(group):
                base = command or "group"
                active = self._active.get(base, 0) + 1
                self._active[base] = active
                self._labels[group] = base if active == 1 else f"{base} {active}"
                self._auto.add(group)
            else:
                # Preserve a user-chosen group name verbatim.
                self._labels[group] = group
        return self._labels[group]

    def release(self, group: str | None) -> None:
        """Mark an auto group as closed so its command name is free to reuse without a number."""
        if group is None or group not in self._auto:
            return  # unknown or user-named group: nothing to release
        label = self._labels.get(group)
        if not label:
            return
        base = label.rsplit(" ", 1)[0] if label[-1:].isdigit() else label
        if self._active.get(base):
            self._active[base] -= 1


