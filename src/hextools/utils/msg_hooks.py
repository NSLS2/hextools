class MsgHookNarrator:
    """
    A bluesky ``RunEngine`` ``msg_hook`` that narrates a plan's activity in plain English.

    Attach an instance to a RunEngine and it will, for every ``Msg`` the RunEngine
    processes, serialize the message, feed it to a :class:`StreamNarrator`, and emit any
    finalized narration lines (printed by default)::

        RE.msg_hook = MsgHookNarrator()

    By default the hook consumes *raw* ``Msg`` objects and serializes them itself. If you
    are feeding it messages that are already serialized (dicts of the documented shape),
    pass ``serialize=False``.

    Parameters
    ----------
    emit : callable, optional
        Called with each finalized narration line (a ``str``). Defaults to :func:`print`.
    show_timestamps : bool, optional
        Prefix each line with the message's human-readable timestamp.
    window : float, optional
        Maximum span, in seconds, over which same-kind messages are joined (see
        :class:`StreamNarrator`).
    serialize : bool, optional
        If True (default), incoming values are treated as raw ``Msg`` objects and
        serialized via :func:`serialize_msg`. If False, they are assumed to already be
        serialized dicts.
    """

    def __init__(
        self,
        *,
        emit: Callable[[str], Any] | None = None,
        show_timestamps: bool = False,
        window: float = 60.0,
        serialize: bool = True,
    ) -> None:
        self._emit = emit if emit is not None else print
        self._serialize = serialize
        self._narrator = StreamNarrator(show_timestamps=show_timestamps, window=window)
        self._listeners: list[Callable[[str], Any]] = []

    def add_listener(self, callback: Callable[[str], Any]) -> None:
        """Also send each finalized line to ``callback`` (called on the RunEngine thread)."""
        self._listeners.append(callback)

    def remove_listener(self, callback: Callable[[str], Any]) -> None:
        if callback in self._listeners:
            self._listeners.remove(callback)

    def _send(self, line: str) -> None:
        self._emit(line)
        for listener in list(self._listeners):
            try:
                listener(line)
            except Exception:
                # A broken listener must not fail the running plan.
                pass

    def __call__(self, msg: Any) -> None:
        """Consume one message (raw ``Msg`` by default); emit any finalized lines."""
        record = msg_to_json_safe_dict(msg) if self._serialize else msg
        for line in self._narrator.push(record):
            self._send(line)

    def due(self, now: float | None = None) -> None:
        """Emit any lines whose buffered run has been idle longer than ``window`` seconds."""
        for line in self._narrator.due(now):
            self._send(line)

    def flush(self) -> None:
        """Emit all remaining buffered lines (call when the plan/stream ends)."""
        for line in self._narrator.flush():
            self._send(line)


